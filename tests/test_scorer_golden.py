def test_sweep_tamil_pp_marker_only_ettirvaadham():
    # PP heading uses ONLY the canonical Tamil step word எதிர்வாதம் (no பூர்வபக்ஷம்).
    # The D2 extractor must still isolate the PP section so the named source counts.
    ans = (
        "முன்மொழிவு: அனுமானம் செல்லுபடியானது.\n"
        "எதிர்வாதம்: நாகார்ஜுன வாதிடுகிறார் அபோஹம் மட்டுமே என்று.\n"
        "சித்தாந்தம்: ஆயினும் இந்த எதிர்வாதம் தவறானது."
    )
    score, det = ev.score_purvapaksha_quality(ans, expected_sources=["Nagarjuna"])
    assert det["broad_philosopher_found"] is True
    assert score == 3, "Tamil எதிர்வாதம் PP marker not honoured by D2 extractor"


def test_sweep_technical_vocab_indic():
    # Native-script technical term (अनुमान) + Indic backref -> D5 == 2.
    sid = "सिद्धांत: तथापि यह आपत्ति गलत है क्योंकि अनुमान वास्तविक है।"
    score, det = ev.score_siddhanta_quality(sid)
    assert det["technical_vocab_found"] is True, "Indic technical vocab undetected"
    assert score == 2


def test_sweep_generic_phrases_indic():
    # Indic vague, un-attributed objection (no name/school) must reach the D2=1 floor.
    ans = (
        "पूर्वपक्ष: कुछ लोग कहते हैं कि यह गलत है।\n"
        "सिद्धांत: तथापि यह ठीक है।"
    )
    score, det = ev.score_purvapaksha_quality(ans, expected_sources=[])
    assert det["broad_philosopher_found"] is False
    assert det["named_school_found"] is False
    assert score == 1, "Indic generic objection not credited the D2=1 floor"
