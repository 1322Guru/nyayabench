# ---------------------------------------------------------------------------
# Bug #5 — confidence calibration must detect native-script natural-language
# hedging (partial credit), not only English / the [CONFIDENCE:] bracket.
# Revert guard: revert CONFIDENCE_PATTERN natural-language half to English-only.
# ---------------------------------------------------------------------------

def test_bug5_golden_native_hedge_partial_credit():
    case = BY_ID["GA-07"]
